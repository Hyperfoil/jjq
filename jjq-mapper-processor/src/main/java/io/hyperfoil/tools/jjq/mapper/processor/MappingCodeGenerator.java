    /** Read expression for an any-getter: always a no-arg method call. */
    private static String anyGetterReadExpr(JqMapperProcessor.AnyInfo anyInfo) {
        return "instance." + anyInfo.getterName() + "()";
    }

    /** Emit the unknown-key forward loop into generated fromJqValue. */
    private static void generateAnySetterForward(StringBuilder sb, String target,
                                                 JqMapperProcessor.AnyInfo anyInfo) {
        sb.append("        if (input instanceof JqObject _uobj) {\n");
        sb.append("            for (int _ui = 0; _ui < _uobj.size(); _ui++) {\n");
        sb.append("                String _uk = _uobj.keyAt(_ui);\n");
        sb.append("                if (!_ANY_KNOWN.contains(_uk)) ").append(target).append(".")
          .append(anyInfo.setterName()).append("(_uk, ");
        if (anyInfo.setterTakesJqValue()) {
            sb.append("_uobj.valueAt(_ui));\n");
        } else {
            sb.append("_uobj.valueAt(_ui).toJavaObject());\n");
        }
        sb.append("            }\n");
        sb.append("        }\n");
    }

    /** Return the Java default value literal for a type name. */
    private static String defaultLiteral(String typeName) {
        return switch (typeName) {
            case "int", "java.lang.Integer" -> "0";
            case "long", "java.lang.Long" -> "0L";
            case "double", "java.lang.Double" -> "0.0";
            case "float", "java.lang.Float" -> "0.0f";
            case "boolean", "java.lang.Boolean" -> "false";
            case "short", "java.lang.Short" -> "(short) 0";
            case "byte", "java.lang.Byte" -> "(byte) 0";
            case "char", "java.lang.Character" -> "'\\0'";
            default -> "null";
        };
    }

    /** Extract the first generic type argument from a parameterized type string like "java.util.List<java.lang.String>". */
    private static String extractGenericArg(String typeName) {
        int start = typeName.indexOf('<');
        int end = typeName.lastIndexOf('>');
        if (start >= 0 && end > start) {
            return typeName.substring(start + 1, end);
        }
        return "java.lang.Object";
    }

    /**
     * A {@code Class} literal for plain types, or a {@code TypeToken} capture
     * for parameterized ones — a parameterized {@code .class} literal is
     * illegal Java (issue #101). The emitted form needs no import (fully
     * qualified) and its type arguments are already fully qualified, so it
     * resolves in any generated package.
     */
    private static String typeLiteral(String typeName) {
        if (typeName.contains("<")) return typeTokenExpr(typeName);
        return typeName + ".class";
    }

    /** {@code new TypeToken<T>(){}.getType()} for a parameterized type string. */
    private static String typeTokenExpr(String typeName) {
        return "new io.hyperfoil.tools.jjq.mapper.TypeToken<" + typeName + ">(){}.getType()";
    }

    /**
     * Deserialization expression for an adapter field: a direct static call
     * whose {@code JqNull} input short-circuits to null without calling
     * (issue #120). {@code from}-String takes scalar text via
     * {@code requireString} (house scalar leniency, containers fail fast).
     */
    private static String adapterExtraction(String typeName, String apply,
            JqMapperProcessor.AdapterInfo adapter) {
        String arg = adapter.fromString()
                ? "requireString(" + apply + ", \"text for " + simpleName(typeName) + "\")"
                : apply;
        return apply + " instanceof JqNull ? null : "
                + typeName + "." + adapter.fromName() + "(" + arg + ")";
    }

    /**
     * Serialization value expression for an adapter field: a direct call
     * (static or instance) that a null field skips without calling, with
     * {@code String} results wrapped null-safely (issue #120).
     */
    private static String adapterSerialization(String typeName, String readExpr,
            JqMapperProcessor.AdapterInfo adapter) {
        String call = adapter.toStatic()
                ? typeName + "." + adapter.toName() + "(" + readExpr + ")"
                : readExpr + "." + adapter.toName() + "()";
        if (adapter.toStringForm()) {
            return "adaptToString(" + readExpr + " == null ? null : " + call + ")";
        }
        return readExpr + " == null ? JqNull.NULL : " + call;
    }

    /** Simple name of a (possibly nested) qualified type name. */
    private static String simpleName(String typeName) {
        return typeName.substring(typeName.lastIndexOf('.') + 1);
    }

    /**
     * Inclusion guard condition for one field, mirroring
     * {@code FieldMapping.shouldInclude} (issue #109). Returns {@code "true"}
     * when the field is unconditional ({@code ALWAYS}, or a primitive under
     * {@code NON_NULL}/{@code NON_EMPTY} — boxed primitives are never null,
     * and the runtime includes every primitive under {@code NON_EMPTY});
     * callers emit a plain put then. Reference-type conditions are null-safe;
     * emptiness uses the parenthesized form (issue #108).
     *
     * @param inclusion the resolved inclusion name ({@code ALWAYS}/{@code NON_NULL}/...)
     * @param expr      the value expression ({@code instance.x()}, getter call, field read)
     * @param typeName  the declared field type (primitives take the unconditional path)
     */
    private static String inclusionCondition(String inclusion, String expr, String typeName) {
        switch (inclusion) {
            case "NON_NULL" -> {
                if (isPrimitiveType(typeName)) return "true";
                return expr + " != null";
            }
            case "NON_EMPTY" -> {
                if (isPrimitiveType(typeName)) return "true";
                if (typeName.equals("java.lang.String")
                        || typeName.startsWith("java.util.List")
                        || typeName.startsWith("java.util.Map")
                        || typeName.startsWith("java.util.Set")
                        || typeName.startsWith("java.util.Collection")) {
                    return expr + " != null && !(" + expr + ").isEmpty()";
                }
                return expr + " != null";
            }
            case "NON_DEFAULT" -> {
                // Boxed mirrors of the primitive rules (null-safe first):
                // shouldInclude excludes ""/0/false/0.0/'\0' for wrappers too.
                return switch (typeName) {
                    case "int", "long", "short", "byte" -> expr + " != 0";
                    case "double", "float" -> expr + " != 0.0";
                    case "boolean" -> expr;
                    case "char" -> expr + " != '\\0'";
                    case "java.lang.String" -> expr + " != null && !(" + expr + ").isEmpty()";
                    case "java.lang.Integer" -> expr + " != null && (int) " + expr + " != 0";
                    case "java.lang.Long" -> expr + " != null && (long) " + expr + " != 0";
                    case "java.lang.Short" -> expr + " != null && (short) " + expr + " != 0";
                    case "java.lang.Byte" -> expr + " != null && (byte) " + expr + " != 0";
                    case "java.lang.Double", "java.lang.Float" ->
                        expr + " != null && (double) " + expr + " != 0.0";
                    case "java.lang.Boolean" -> expr + " != null && " + expr;
                    case "java.lang.Character" -> expr + " != null && (char) " + expr + " != '\\0'";
                    case "java.math.BigDecimal" ->
                        expr + " != null && " + expr + ".doubleValue() != 0.0";
                    default -> expr + " != null";
                };
            }
            default -> {
                return "true";
            }
        }
    }

    /** The eight JVM primitive type names. */
    private static boolean isPrimitiveType(String typeName) {
        return switch (typeName) {
            case "boolean", "byte", "short", "int", "long", "float", "double", "char" -> true;
            default -> false;
        };
    }

    /**
     * Generate the complete Java source for a POJO _JqMapping class.
     * Uses no-arg constructor + setter calls for deserialization,
     * and getter calls for serialization.
     */
    static String generateForClass(String packageName, String classSimpleName, String classQualifiedName,
                                    String mappingClassName, List<JqMapperProcessor.PropertyInfo> properties,
                                    JqMapperProcessor.AnyInfo anyInfo) {
        var sb = new StringBuilder(1024);

        if (!packageName.isEmpty()) {
            sb.append("package ").append(packageName).append(";\n\n");
        }

        // POJOs always use JqProgram for field access (interning advantage, see issue #76)
        boolean needsJqProgram = properties.stream().anyMatch(p -> !p.ignored());

        if (needsJqProgram) sb.append("import io.hyperfoil.tools.jjq.JqProgram;\n");
        sb.append("import io.hyperfoil.tools.jjq.mapper.GeneratedMapping;\n");
        sb.append("import io.hyperfoil.tools.jjq.mapper.JqMapper;\n");
        sb.append("import io.hyperfoil.tools.jjq.value.*;\n\n");

        sb.append("/**\n");
        sb.append(" * Generated mapping for {@link ").append(classQualifiedName).append("}.\n");
        sb.append(" * Do not edit — regenerated by jjq-mapper-processor.\n");
        sb.append(" */\n");
        sb.append("public final class ").append(mappingClassName);
        sb.append(" extends GeneratedMapping<").append(classSimpleName).append("> {\n\n");

        // Static JqProgram fields for all non-ignored fields (interning advantage)
        for (var prop : properties) {
            if (!prop.ignored()) {
                sb.append("    private static final JqProgram P_")
                  .append(prop.name().toUpperCase())
                  .append(" = JqProgram.compile(\"")
                  .append(escapeJava(prop.jqExpr()))
                  .append("\");\n");
            }
        }
        // Static converter fields for @JqConverter annotations (mirrors record path)
        var emittedPojoConverters = new java.util.HashSet<String>();
        for (var prop : properties) {
            if (!prop.ignored() && prop.converterClass() != null
                    && emittedPojoConverters.add(prop.converterField())) {
                sb.append("    private static final io.hyperfoil.tools.jjq.mapper.ValueConverter<?> ")
                  .append(prop.converterField())
                  .append(" = new ").append(prop.converterClass()).append("();\n");
            }
        }
        // Cached field handles for the private-field fallback (issue #104):
        // same setAccessible semantics as the reflection path, resolved once.
        var fallbackProps = properties.stream().filter(MappingCodeGenerator::needsFieldHandle).toList();
        for (var prop : fallbackProps) {
            sb.append("    private static final java.lang.reflect.Field F_")
              .append(prop.name().toUpperCase())
              .append(";\n");
        }
        if (!fallbackProps.isEmpty()) {
            sb.append("\n    static {\n");
            sb.append("        try {\n");
            for (var prop : fallbackProps) {
                String handle = "F_" + prop.name().toUpperCase();
                sb.append("            ").append(handle).append(" = ")
                  .append(classSimpleName).append(".class.getDeclaredField(\"")
                  .append(prop.name()).append("\");\n");
                sb.append("            ").append(handle).append(".setAccessible(true);\n");
            }
            sb.append("        } catch (NoSuchFieldException _e) {\n");
            sb.append("            throw new ExceptionInInitializerError(_e);\n");
            sb.append("        }\n");
            sb.append("    }\n");
        }
        if (anyInfo.hasSetter()) {
            generateAnyKnownSet(sb, knownJsonNamesPojo(properties));
        }
        sb.append("\n");

        // fromJqValue: no-arg constructor + setters
        sb.append("    @Override\n");
        sb.append("    public ").append(classSimpleName).append(" fromJqValue(JqValue input, JqMapper mapper) {\n");
        sb.append("        ").append(classSimpleName).append(" instance = new ").append(classSimpleName).append("();\n");

        for (var prop : properties) {
            if (prop.ignored() || prop.skipDeserialize()) continue;
            String apply = "P_" + prop.name().toUpperCase() + ".apply(input)";
            String writeExpr = buildExtraction(prop, apply);

            String statement;
            if (prop.isPublicField() && prop.setterName() == null) {
                // Direct public field write
                statement = "instance." + prop.name() + " = " + writeExpr + ";";
            } else if (prop.setterName() != null) {
                // Setter method
                statement = "instance." + prop.setterName() + "(" + writeExpr + ");";
            } else if (!prop.privateField()) {
                // Same-package field (package-private/protected): direct write
                // is legal (mirrors the read fallback in resolvePojoReadExpr)
                statement = "instance." + prop.name() + " = " + writeExpr + ";";
            } else if (!prop.finalField()) {
                // Private non-final field: cached reflection handle, same
                // setAccessible semantics as the reflection path (issue #104)
                statement = "writeField(F_" + prop.name().toUpperCase() + ", instance, "
                        + writeExpr + ");";
            } else {
                // Private final field — read-only (the runtime path skips it too)
                continue;
            }
            if (prop.hasJqField()) {
                // Custom @JqField expression: absence is unprovable, write always
                sb.append("        ").append(statement).append("\n");
            } else if (isFalliblePojoExtraction(prop)) {
                // Fallible conversion: track the field in the failure path (issue #84)
                sb.append("        if (input.has(\"").append(escapeJava(prop.jsonName())).append("\")) {\n");
                sb.append("            try {\n");
                sb.append("                ").append(statement).append("\n");
                sb.append("            } catch (io.hyperfoil.tools.jjq.mapper.JqMapperException _e) {\n");
                sb.append("                throw _e.prependPath(\"").append(escapeJava(prop.jsonName())).append("\");\n");
                sb.append("            }\n");
                sb.append("        }\n");
            } else {
                // Absent keys leave field initializers in place (issue #82).
                // Explicit nulls still take the write path. has() is null-safe.
                sb.append("        if (input.has(\"").append(escapeJava(prop.jsonName())).append("\")) ")
                        .append(statement).append("\n");
            }
        }

        if (anyInfo.hasSetter()) {
            generateAnySetterForward(sb, "instance", anyInfo);
        }
        sb.append("        return instance;\n");
        sb.append("    }\n\n");

        // toJqValue: getter calls
        int activeCount = (int) properties.stream().filter(p -> !p.ignored()).count();
        boolean hasInclusion = properties.stream()
                .anyMatch(p -> !p.ignored() && !"ALWAYS".equals(p.inclusion()));

        sb.append("    @Override\n");
        sb.append("    public JqValue toJqValue(").append(classSimpleName).append(" instance, JqMapper mapper) {\n");

        if (!hasInclusion && !anyInfo.hasGetter()) {
            // Fast path: no inclusion filtering
            sb.append("        return JqObject.builder(").append(activeCount).append(")\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                sb.append("            .putUnchecked(\"").append(prop.jsonName()).append("\", ");
                generateSerializationValueForPojo(sb, prop, readExpr);
                sb.append(")\n");
            }
            sb.append("            .build();\n");
        } else if (!hasInclusion) {
            // Fast path with any-getter extras appended afterwards (issue #87)
            sb.append("        var _b = JqObject.builder(").append(activeCount).append(")\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                sb.append("            .putUnchecked(\"").append(prop.jsonName()).append("\", ");
                generateSerializationValueForPojo(sb, prop, readExpr);
                sb.append(")\n");
            }
            sb.append("            ;\n");
            sb.append("        putExtras(_b, ").append(anyGetterReadExpr(anyInfo)).append(", mapper);\n");
            sb.append("        return _b.build();\n");
        } else {
            // Inclusion filtering: keys unique — use putUnchecked
            sb.append("        var _b = JqObject.builder(").append(activeCount).append(");\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if ("ALWAYS".equals(prop.inclusion())) {
                    sb.append("        _b.putUnchecked(\"").append(prop.jsonName()).append("\", ");
                    generateSerializationValueForPojo(sb, prop, readExpr);
                    sb.append(");\n");
                } else {
                    generatePojoInclusionCheck(sb, prop, readExpr);
                }
            }
            if (anyInfo.hasGetter()) {
                sb.append("        putExtras(_b, ").append(anyGetterReadExpr(anyInfo)).append(", mapper);\n");
            }
            sb.append("        return _b.build();\n");
        }

        sb.append("    }\n\n");

        // appendJson — direct-to-JSON, bypasses JqValue tree
        generateAppendJsonForPojo(sb, classSimpleName, properties, anyInfo);

        // appendJsonBytes — direct-to-bytes, bypasses JqValue tree
        generateAppendJsonBytesForPojo(sb, classSimpleName, properties, anyInfo);

        // type()
        sb.append("    @Override\n");
        sb.append("    public Class<").append(classSimpleName).append("> type() {\n");
        sb.append("        return ").append(classSimpleName).append(".class;\n");
        sb.append("    }\n");

        sb.append("}\n");
        return sb.toString();
    }

    /**
     * Generate appendJson for POJOs — same pattern as records but uses getter/field access.
     */
    private static void generateAppendJsonForPojo(StringBuilder sb, String classSimpleName,
                                                    List<JqMapperProcessor.PropertyInfo> properties,
                                                    JqMapperProcessor.AnyInfo anyInfo) {
        boolean hasInclusion = properties.stream()
                .anyMatch(p -> !p.ignored() && !"ALWAYS".equals(p.inclusion()));

        sb.append("    @Override\n");
        sb.append("    public void appendJson(").append(classSimpleName)
          .append(" instance, StringBuilder _sb, JqMapper mapper) {\n");
        if (anyInfo.hasGetter()) {
            // Any-getter extras need tree materialization — fall back (issue #87).
            // Emitting only the fallback: body after return would be unreachable code.
            sb.append("        toJqValue(instance, mapper).appendTo(_sb);\n");
            sb.append("    }\n\n");
            return;
        }
        sb.append("        _sb.append('{');\n");

        if (!hasInclusion) {
            boolean first = true;
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if (!first) sb.append("        _sb.append(',');\n");
                sb.append("        _sb.append(\"\\\"").append(escapeJava(prop.jsonName())).append("\\\":\");\n");
                appendJsonValueForPojo(sb, prop, readExpr);
                first = false;
            }
        } else {
            sb.append("        boolean _sep = false;\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if ("ALWAYS".equals(prop.inclusion())) {
                    sb.append("        if (_sep) _sb.append(','); _sep = true;\n");
                    sb.append("        _sb.append(\"\\\"").append(escapeJava(prop.jsonName())).append("\\\":\");\n");
                    appendJsonValueForPojo(sb, prop, readExpr);
                } else {
                    appendJsonFieldWithInclusionForPojo(sb, prop, readExpr);
                }
            }
        }

        sb.append("        _sb.append('}');\n");
        sb.append("    }\n\n");
    }


    /**
     * Emit builder binding into POJO {@code fromJqValue}: one chained call
     * per bound field (absent keys keep builder defaults, explicit nulls
     * still write — same leniency as the setter path), then the terminal
     * build call with wrapped failures. Mirrors the runtime builder branch.
     */
    private static void emitPojoBuilderBlock(StringBuilder sb, String classSimpleName,
                                             List<JqMapperProcessor.PropertyInfo> properties,
                                             JqMapperProcessor.BuilderInfo builder,
                                             java.util.Map<String, String> typeRefs) {
        var byJson = new java.util.HashMap<String, JqMapperProcessor.BuilderFieldInfo>();
        for (var b : builder.bound()) byJson.put(b.jsonName(), b);
        for (var prop : properties) {
            if (prop.ignored() || prop.skipDeserialize()) continue;
            var b = byJson.get(prop.jsonName());
            if (b == null) continue; // cannot happen (fail fast at processing)
            String writeExpr;
            String optVar;
            if (prop.hasJqField()) {
                String apply = "P_" + prop.name().toUpperCase() + ".apply(input)";
                writeExpr = buildExtraction(prop, apply, typeRefs);
                optVar = null;
            } else {
                optVar = "_v_" + prop.name();
                sb.append("        var ").append(optVar).append(" = input.tryGet(K_")
                  .append(prop.name().toUpperCase()).append(");\n");
                writeExpr = buildExtraction(prop, optVar + ".get()", typeRefs);
            }
            String invoke = b.isVoid()
                    ? "_b." + b.binderName() + "(" + writeExpr + ")"
                    : "_b = _b." + b.binderName() + "(" + writeExpr + ")";
            if (prop.hasJqField()) {
                sb.append("        ").append(invoke).append(";\n");
            } else if (isFalliblePojoExtraction(prop)) {
                sb.append("        if (").append(optVar).append(".isPresent()) {\n");
                sb.append("            try {\n");
                sb.append("                ").append(invoke).append(";\n");
                sb.append("            } catch (io.hyperfoil.tools.jjq.mapper.JqMapperException _e) {\n");
                sb.append("                throw _e.prependPath(\"").append(escapeJava(prop.jsonName())).append("\");\n");
                sb.append("            }\n");
                sb.append("        }\n");
            } else {
                sb.append("        if (").append(optVar).append(".isPresent()) ").append(invoke).append(";\n");
            }
        }
        sb.append("        ").append(classSimpleName).append(" instance;\n");
        sb.append("        try {\n");
        sb.append("            instance = _b.").append(builder.build()).append("();\n");
        emitCreatorCatch(sb, classSimpleName, builder.label());
    }

    /**
     * Write statement for a POJO property given the value expression, or null
     * when the property is read-only (private final with no setter — the
     * runtime path skips it too). Shared by the slow loop and the positional
     * fast path.
     */
    private static String pojoWriteStatement(JqMapperProcessor.PropertyInfo prop, String writeExpr) {
        if (prop.isPublicField() && prop.setterName() == null) {
            // Direct public field write
            return "instance." + prop.name() + " = " + writeExpr + ";";
        } else if (prop.setterName() != null) {
            // Setter method
            return "instance." + prop.setterName() + "(" + writeExpr + ");";
        } else if (!prop.privateField()) {
            // Same-package field (package-private/protected): direct write
            // is legal (mirrors the read fallback in resolvePojoReadExpr)
            return "instance." + prop.name() + " = " + writeExpr + ";";
        } else if (!prop.finalField()) {
            // Private non-final field: cached reflection handle, same
            // setAccessible semantics as the reflection path (issue #104)
            return "writeField(F_" + prop.name().toUpperCase() + ", instance, "
                    + writeExpr + ");";
        }
        return null;
    }

    /**
     * Resolve read expression for a POJO field. Mirrors the reflection
     * fallback ladder (issue #104): public field or same-package field
     * (generated code shares the package) read directly; usable getter by
     * call; private field with no usable getter via a cached reflection
     * handle. Returns null only for ignored/inaccessible properties, which
     * callers skip.
     */
    private static String resolvePojoReadExpr(JqMapperProcessor.PropertyInfo prop) {
        if (prop.getterName() != null) {
            return "instance." + prop.getterName() + "()";
        }
        if (!prop.privateField()) {
            // Public, package-private, or protected field in the same package:
            // direct access is legal.
            return "instance." + prop.name();
        }
        return readFallbackExpr(prop);
    }

    /**
     * Read expression through a cached reflection handle for a private field
     * with no usable getter. Primitive-typed reads avoid boxing.
     */
    private static String readFallbackExpr(JqMapperProcessor.PropertyInfo prop) {
        String handle = "F_" + prop.name().toUpperCase();
        return switch (prop.typeName()) {
            case "boolean" -> "readBooleanField(" + handle + ", instance)";
            case "byte" -> "readByteField(" + handle + ", instance)";
            case "short" -> "readShortField(" + handle + ", instance)";
            case "int" -> "readIntField(" + handle + ", instance)";
            case "long" -> "readLongField(" + handle + ", instance)";
            case "float" -> "readFloatField(" + handle + ", instance)";
            case "double" -> "readDoubleField(" + handle + ", instance)";
            case "char" -> "readCharField(" + handle + ", instance)";
            default -> "(" + prop.typeName() + ") readField(" + handle + ", instance)";
        };
    }

    /**
     * True when a property needs a cached reflection handle: a private field
     * with no usable getter that is actually read or written by generated code
     * (active direction only — mirrors the skip logic at the emission sites).
     */
    private static boolean needsFieldHandle(JqMapperProcessor.PropertyInfo prop) {
        if (prop.ignored() || !prop.privateField() || prop.getterName() != null) return false;
        if (!prop.skipSerialize()) return true;
        return !prop.skipDeserialize() && !prop.finalField()
                && !prop.isPublicField() && prop.setterName() == null;
    }


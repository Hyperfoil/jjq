    /**
     * Sort bound fields in place for serialization: explicit wires first
     * (validated), tail by declaration or alphabetically. Call only after
     * all deserialization emission (constructor alignment depends on
     * declaration order); only serialization follows. No-op when unordered.
     */
    private static <T> void sortSerView(java.util.List<T> items,
                                        java.util.function.Function<T, String> jsonName,
                                        io.hyperfoil.tools.jjq.mapper.JqOrder.Spec order) {
        if (order == null) return;
        var rank = new java.util.HashMap<String, Integer>();
        for (int i = 0; i < order.explicit().size(); i++) {
            rank.putIfAbsent(order.explicit().get(i), i);
        }
        items.sort((a, b) -> {
            Integer ra = rank.get(jsonName.apply(a));
            Integer rb = rank.get(jsonName.apply(b));
            if (ra != null && rb != null) return Integer.compare(ra, rb);
            if (ra != null) return -1;
            if (rb != null) return 1;
            if (order.alphabetic()) return jsonName.apply(a).compareTo(jsonName.apply(b));
            return 0;
        });
    }

    /** Emit the unknown-key forward loop into generated fromJqValue. */
    private static void generateAnySetterForward(StringBuilder sb, String target,
                                                 JqMapperProcessor.AnyInfo anyInfo) {
        sb.append("        if (input instanceof JqObject _uobj) {\n");
        sb.append("            for (int _ui = 0; _ui < _uobj.size(); _ui++) {\n");
        sb.append("                String _uk = _uobj.keyAt(_ui);\n");
        sb.append("                if (!_ANY_KNOWN.contains(_uk)) ").append(target).append(".")
          .append(anyInfo.setterName()).append("(_uk, ");
        if (anyInfo.setterTakesJqValue()) {
            sb.append("_uobj.valueAt(_ui));\n");
        } else {
            sb.append("_uobj.valueAt(_ui).toJavaObject());\n");
        }
        sb.append("            }\n");
        sb.append("        }\n");
    }

    /** Return the Java default value literal for a type name. */
    private static String defaultLiteral(String typeName) {
        return switch (typeName) {
            case "int", "java.lang.Integer" -> "0";
            case "long", "java.lang.Long" -> "0L";
            case "double", "java.lang.Double" -> "0.0";
            case "float", "java.lang.Float" -> "0.0f";
            case "boolean", "java.lang.Boolean" -> "false";
            case "short", "java.lang.Short" -> "(short) 0";
            case "byte", "java.lang.Byte" -> "(byte) 0";
            case "char", "java.lang.Character" -> "'\\0'";
            default -> "null";
        };
    }

    /** Extract the first generic type argument from a parameterized type string like "java.util.List<java.lang.String>". */
    private static String extractGenericArg(String typeName) {
        int start = typeName.indexOf('<');
        int end = typeName.lastIndexOf('>');
        if (start >= 0 && end > start) {
            return typeName.substring(start + 1, end);
        }
        return "java.lang.Object";
    }

    /**
     * A {@code Class} literal for plain types, or the hoisted
     * {@code TypeToken} constant for parameterized ones — a parameterized
     * {@code .class} literal is illegal Java (issue #101). The constants are
     * collected per mapping up front; a type missing from the map falls back
     * to the inline capture (defensive — the pre-scan covers every emitted
     * site).
     */
    private static String typeLiteral(String typeName, java.util.Map<String, String> typeRefs) {
        if (typeName.contains("<")) return typeRef(typeName, typeRefs);
        return typeName + ".class";
    }

    /**
     * Emitted type reference for a parameterized type: the hoisted
     * {@code T_} constant when collected, else the inline capture.
     */
    private static String typeRef(String typeName, java.util.Map<String, String> typeRefs) {
        String constant = typeRefs.get(typeName);
        return constant != null ? constant : typeTokenExpr(typeName);
    }

    /**
     * Collect the parameterized types one component references, including
     * the inner type of {@code Optional} fields (the Optional conversion
     * binds generic inners through the same token). Keyed by type so
     * repeated shapes share one constant.
     *
     * @param pojoBinding true on the POJO path, where every parameterized
     *        field routes through the mapper default branch; records emit
     *        specialized forms for {@code List} (non-generic elements) and
     *        {@code Optional} (ternary) that never reference the whole-type
     *        token, so only actually-referenced shapes are collected
     */
    private static void collectTypeRef(String typeName, String fieldName,
            java.util.Map<String, String> typeRefs, boolean pojoBinding) {
        if (typeName.contains("<") && (pojoBinding || referencesTypeToken(typeName))) {
            typeRefs.putIfAbsent(typeName, "T_" + fieldName.toUpperCase());
        }
        if (typeName.startsWith("java.util.Optional<")) {
            String inner = extractGenericArg(typeName);
            if (inner.contains("<")) {
                typeRefs.putIfAbsent(inner, "T_" + fieldName.toUpperCase());
            }
        }
    }

    /**
     * Whether the record-path emission references the whole parameterized
     * type through a token: {@code Map} and every other generic do,
     * {@code Optional} binds through the empty-or-present ternary, and
     * {@code List} only when its element is itself generic (otherwise the
     * element-class {@code _toList} form applies).
     */
    private static boolean referencesTypeToken(String typeName) {
        if (typeName.startsWith("java.util.Optional<")) return false;
        if (typeName.startsWith("java.util.List<")) {
            return extractGenericArg(typeName).contains("<");
        }
        return true;
    }

    /** {@code new TypeToken<T>(){}.getType()} for a parameterized type string. */
    private static String typeTokenExpr(String typeName) {
        return "new io.hyperfoil.tools.jjq.mapper.TypeToken<" + typeName + ">(){}.getType()";
    }

    /**
     * Deserialization expression for an adapter field: a direct static call
     * whose {@code JqNull} input short-circuits to null without calling
     * (issue #120). {@code from}-String takes scalar text via
     * {@code requireString} (house scalar leniency, containers fail fast).
     */
    private static String adapterExtraction(String typeName, String apply,
            JqMapperProcessor.AdapterInfo adapter) {
        String arg = adapter.fromString()
                ? "requireString(" + apply + ", \"text for " + simpleName(typeName) + "\")"
                : apply;
        return apply + " instanceof JqNull ? null : "
                + typeName + "." + adapter.fromName() + "(" + arg + ")";
    }

    /**
     * Serialization value expression for an adapter field: a direct call
     * (static or instance) that a null field skips without calling, with
     * {@code String} results wrapped null-safely (issue #120).
     */
    private static String adapterSerialization(String typeName, String readExpr,
            JqMapperProcessor.AdapterInfo adapter) {
        String call = adapter.toStatic()
                ? typeName + "." + adapter.toName() + "(" + readExpr + ")"
                : readExpr + "." + adapter.toName() + "()";
        if (adapter.toStringForm()) {
            return "adaptToString(" + readExpr + " == null ? null : " + call + ")";
        }
        return readExpr + " == null ? JqNull.NULL : " + call;
    }

    /** Simple name of a (possibly nested) qualified type name. */
    private static String simpleName(String typeName) {
        return typeName.substring(typeName.lastIndexOf('.') + 1);
    }

    /**
     * Inclusion guard condition for one field, mirroring
     * {@code FieldMapping.shouldInclude} (issue #109). Returns {@code "true"}
     * when the field is unconditional ({@code ALWAYS}, or a primitive under
     * {@code NON_NULL}/{@code NON_EMPTY} — boxed primitives are never null,
     * and the runtime includes every primitive under {@code NON_EMPTY});
     * callers emit a plain put then. Reference-type conditions are null-safe;
     * emptiness uses the parenthesized form (issue #108).
     *
     * @param inclusion the resolved inclusion name ({@code ALWAYS}/{@code NON_NULL}/...)
     * @param expr      the value expression ({@code instance.x()}, getter call, field read)
     * @param typeName  the declared field type (primitives take the unconditional path)
     */
    private static String inclusionCondition(String inclusion, String expr, String typeName) {
        switch (inclusion) {
            case "NON_NULL" -> {
                if (isPrimitiveType(typeName)) return "true";
                return expr + " != null";
            }
            case "NON_EMPTY" -> {
                if (isPrimitiveType(typeName)) return "true";
                if (typeName.equals("java.lang.String")
                        || typeName.startsWith("java.util.List")
                        || typeName.startsWith("java.util.Map")
                        || typeName.startsWith("java.util.Set")
                        || typeName.startsWith("java.util.Collection")) {
                    return expr + " != null && !(" + expr + ").isEmpty()";
                }
                return expr + " != null";
            }
            case "NON_DEFAULT" -> {
                // Boxed mirrors of the primitive rules (null-safe first):
                // shouldInclude excludes ""/0/false/0.0/'\0' for wrappers too.
                return switch (typeName) {
                    case "int", "long", "short", "byte" -> expr + " != 0";
                    case "double", "float" -> expr + " != 0.0";
                    case "boolean" -> expr;
                    case "char" -> expr + " != '\\0'";
                    case "java.lang.String" -> expr + " != null && !(" + expr + ").isEmpty()";
                    case "java.lang.Integer" -> expr + " != null && (int) " + expr + " != 0";
                    case "java.lang.Long" -> expr + " != null && (long) " + expr + " != 0";
                    case "java.lang.Short" -> expr + " != null && (short) " + expr + " != 0";
                    case "java.lang.Byte" -> expr + " != null && (byte) " + expr + " != 0";
                    case "java.lang.Double", "java.lang.Float" ->
                        expr + " != null && (double) " + expr + " != 0.0";
                    case "java.lang.Boolean" -> expr + " != null && " + expr;
                    case "java.lang.Character" -> expr + " != null && (char) " + expr + " != '\\0'";
                    case "java.math.BigDecimal" ->
                        expr + " != null && " + expr + ".doubleValue() != 0.0";
                    case "java.math.BigInteger" ->
                        expr + " != null && " + expr + ".signum() != 0";
                    default -> expr + " != null";
                };
            }
            default -> {
                return "true";
            }
        }
    }

    /** The eight JVM primitive type names. */
    private static boolean isPrimitiveType(String typeName) {
        return switch (typeName) {
            case "boolean", "byte", "short", "int", "long", "float", "double", "char" -> true;
            default -> false;
        };
    }

    /**
     * Generate the complete Java source for a POJO _JqMapping class.
     * Uses no-arg constructor + setter calls for deserialization,
     * and getter calls for serialization.
     */
    static String generateForClass(String packageName, String classSimpleName, String classQualifiedName,
                                    String mappingClassName, List<JqMapperProcessor.PropertyInfo> properties,
                                    JqMapperProcessor.AnyInfo anyInfo,
                                    JqMapperProcessor.CreatorInfo creator,
                                    JqMapperProcessor.BuilderInfo builder,
                                    List<String> required, io.hyperfoil.tools.jjq.mapper.JqOrder.Spec order,
                                    java.util.function.Predicate<String> mappedTypeNames) {
        var sb = new StringBuilder(1024);

        if (!packageName.isEmpty()) {
            sb.append("package ").append(packageName).append(";\n\n");
        }

        // POJOs use JqProgram only for custom @JqField expressions now;
        // direct fields go through tryGet (single lookup, interned literal keys)
        boolean needsJqProgram = properties.stream().anyMatch(p -> !p.ignored() && p.hasJqField());

        if (needsJqProgram) sb.append("import io.hyperfoil.tools.jjq.JqProgram;\n");
        sb.append("import io.hyperfoil.tools.jjq.mapper.GeneratedMapping;\n");
        sb.append("import io.hyperfoil.tools.jjq.mapper.JqMapper;\n");
        sb.append("import io.hyperfoil.tools.jjq.value.*;\n\n");

        sb.append("/**\n");
        sb.append(" * Generated mapping for {@link ").append(classQualifiedName).append("}.\n");
        sb.append(" * Do not edit — regenerated by jjq-mapper-processor.\n");
        sb.append(" */\n");
        sb.append("public final class ").append(mappingClassName);
        sb.append(" extends GeneratedMapping<").append(classSimpleName).append("> {\n\n");

        // Static JqProgram fields for custom @JqField expressions only;
        // direct fields use tryGet with interned literal keys (no program needed)
        for (var prop : properties) {
            if (!prop.ignored() && prop.hasJqField()) {
                sb.append("    private static final JqProgram P_")
                  .append(prop.name().toUpperCase())
                  .append(" = JqProgram.compile(\"")
                  .append(escapeJava(prop.jqExpr()))
                  .append("\");\n");
            }
        }
        // Interned key constants for direct tryGet lookups: canonical instances
        // hit the JqObject identity fast path against parsed docs.
        // Creator wire constants use a C_ prefix (a creator wire may equal a
        // property name, and K_ is already taken by the property).
        for (var prop : properties) {
            if (!prop.ignored() && !prop.skipDeserialize() && !prop.hasJqField()) {
                sb.append("    private static final String K_")
                  .append(prop.name().toUpperCase())
                  .append(" = JqValues.internFieldName(\"")
                  .append(escapeJava(prop.jsonName()))
                  .append("\");\n");
            }
        }
        java.util.Set<String> creatorWires = new java.util.HashSet<>();
        if (creator != null && !creator.delegating()) {
            for (var p : creator.params()) {
                creatorWires.add(p.jsonName());
                sb.append("    private static final String C_")
                  .append(p.name().toUpperCase())
                  .append(" = JqValues.internFieldName(\"")
                  .append(escapeJava(p.jsonName()))
                  .append("\");\n");
            }
        }
        // Static converter fields for @JqConverter annotations (mirrors record path)
        var emittedPojoConverters = new java.util.HashSet<String>();
        for (var prop : properties) {
            if (!prop.ignored() && prop.converterClass() != null
                    && emittedPojoConverters.add(prop.converterField())) {
                sb.append("    private static final io.hyperfoil.tools.jjq.mapper.ValueConverter<?> ")
                  .append(prop.converterField())
                  .append(" = new ").append(prop.converterClass()).append("();\n");
            }
        }
        if (creator != null) {
            for (var p : creator.params()) {
                if (p.converterClass() != null
                        && emittedPojoConverters.add(p.converterField())) {
                    sb.append("    private static final io.hyperfoil.tools.jjq.mapper.ValueConverter<?> ")
                      .append(p.converterField())
                      .append(" = new ").append(p.converterClass()).append("();\n");
                }
            }
        }
        emitPojoKeyConstants(sb, properties);
        // Hoisted generic types (same as the record path): one TypeToken
        // constant per parameterized shape instead of a per-call anonymous
        // instance plus reflective superclass walk.
        var typeRefs = new java.util.LinkedHashMap<String, String>();
        for (var prop : properties) collectTypeRef(prop.typeName(), prop.name(), typeRefs, true);
        if (creator != null && !creator.delegating()) {
            for (var p : creator.params()) collectTypeRef(p.typeName(), p.name(), typeRefs, true);
        }
        for (var entry : typeRefs.entrySet()) {
            sb.append("    private static final java.lang.reflect.Type ").append(entry.getValue())
              .append(" = new io.hyperfoil.tools.jjq.mapper.TypeToken<").append(entry.getKey())
              .append(">(){}.getType();\n");
        }
        if (!required.isEmpty()) {
            sb.append("    private static final java.util.List<String> _REQUIRED = java.util.List.of(");
            for (int i = 0; i < required.size(); i++) {
                if (i > 0) sb.append(", ");
                sb.append("\"").append(escapeJava(required.get(i))).append("\"");
            }
            sb.append(");\n");
        }
        // Static formatters for @JqFormat properties (shared by deser and ser)
        for (var prop : properties) {
            if (!prop.ignored() && prop.format() != null) {
                sb.append("    private static final java.time.format.DateTimeFormatter ")
                  .append(formatConst(prop.name()))
                  .append(" = io.hyperfoil.tools.jjq.mapper.TypeConverter.formatterFor(\"")
                  .append(escapeJava(prop.format().pattern())).append("\", \"")
                  .append(escapeJava(prop.format().timezone())).append("\", \"")
                  .append(escapeJava(prop.format().locale())).append("\");\n");
            }
        }
        // Cached field handles for the private-field fallback (issue #104):
        // same setAccessible semantics as the reflection path, resolved once.
        var fallbackProps = properties.stream().filter(MappingCodeGenerator::needsFieldHandle).toList();
        for (var prop : fallbackProps) {
            sb.append("    private static final java.lang.reflect.Field F_")
              .append(prop.name().toUpperCase())
              .append(";\n");
        }
        if (!fallbackProps.isEmpty()) {
            sb.append("\n    static {\n");
            sb.append("        try {\n");
            for (var prop : fallbackProps) {
                String handle = "F_" + prop.name().toUpperCase();
                sb.append("            ").append(handle).append(" = ")
                  .append(classSimpleName).append(".class.getDeclaredField(\"")
                  .append(prop.name()).append("\");\n");
                sb.append("            ").append(handle).append(".setAccessible(true);\n");
            }
            sb.append("        } catch (NoSuchFieldException _e) {\n");
            sb.append("            throw new ExceptionInInitializerError(_e);\n");
            sb.append("        }\n");
            sb.append("    }\n");
        }
        boolean hasPojoDelegating = creator != null && creator.delegating();
        boolean hasPojoCreator = creator != null && !creator.delegating();
        if (anyInfo.hasSetter()) {
            generateAnyKnownSet(sb, knownJsonNamesPojo(properties));
        } else if (hasPojoCreator) {
            // Creator wires bind too (a creator-only name must not fail).
            var strictNames = new java.util.ArrayList<>(knownJsonNamesPojo(properties));
            for (var p : creator.params()) {
                if (!strictNames.contains(p.jsonName())) strictNames.add(p.jsonName());
            }
            generateStrictKnownSet(sb, strictNames);
        } else if (creator == null) {
            generateStrictKnownSet(sb, knownJsonNamesPojo(properties));
        }
        // (Delegating creators mismatch objects before any scan — no set.)
        sb.append("\n");

        // Positional fast path (same eligibility rule as records): every
        // non-ignored property binds directly, so an ordered doc with exactly
        // the bindable keys skips all lookups — pointer compares only.
        boolean pojoPositionalEligible = properties.stream()
                .filter(p -> !p.ignored())
                .allMatch(p -> !p.hasJqField());
        java.util.List<JqMapperProcessor.PropertyInfo> pojoPositional = pojoPositionalEligible
                ? properties.stream()
                    .filter(p -> !p.ignored() && !p.skipDeserialize()
                        && pojoWriteStatement(p, "null") != null)
                    .toList()
                : java.util.List.of();

        // fromJqValue: no-arg constructor + setters (or creator)
        sb.append("    @Override\n");
        sb.append("    public ").append(classSimpleName).append(" fromJqValue(JqValue input, JqMapper mapper) {\n");
        emitObjectShapeGate(sb, classSimpleName, properties.stream()
                .filter(p -> !p.ignored() && !p.skipDeserialize())
                .anyMatch(JqMapperProcessor.PropertyInfo::hasJqField));
        if (hasPojoDelegating) {
            // Delegating creator owns binding: null stays lenient, objects
            // mismatch (creator validation cannot be bypassed), scalars convert.
            sb.append("        if (input == null || input instanceof JqNull) return null;\n");
            sb.append("        if (input instanceof JqObject) throw mismatchObject(input, \"").append(classSimpleName).append("\");\n");
            sb.append("        try {\n");
            sb.append("            return ").append(creator.constructPrefix());
            sb.append(buildExtraction(creatorProperty(creator.params().get(0)), "input", typeRefs));
            sb.append(");\n");
            emitCreatorCatch(sb, classSimpleName, creator.label());
        } else if (hasPojoCreator) {
            for (int i = 0; i < creator.params().size(); i++) {
                var p = creator.params().get(i);
                sb.append("        var _carg").append(i).append(" = ")
                  .append(buildExtraction(creatorProperty(p),
                          "input.tryGet(C_" + p.name().toUpperCase() + ").orElse(JqNull.NULL)", typeRefs))
                  .append(";\n");
            }
            sb.append("        ").append(classSimpleName).append(" instance;\n");
            sb.append("        try {\n");
            sb.append("            instance = ")
              .append(creator.constructPrefix());
            for (int i = 0; i < creator.params().size(); i++) {
                if (i > 0) sb.append(", ");
                sb.append("_carg").append(i);
            }
            sb.append(");\n");
            emitCreatorCatch(sb, classSimpleName, creator.label());
        } else if (builder != null) {
            // Builder binding: instance materializes at the end (see below);
            // only the builder is constructed here.
            sb.append("        ").append(builder.builderSourceName()).append(" _b = ")
              .append(builder.factory()).append(";\n");
        } else {
            sb.append("        ").append(classSimpleName).append(" instance = new ").append(classSimpleName).append("();\n");
        }

        if (!pojoPositional.isEmpty() && creator == null && builder == null) {
            // Ordered docs with exactly the bindable keys bind by index.
            // Anything else (reordered/extra/missing keys, non-objects) falls
            // through to the slow path, which also re-attributes failures.
            // Exact keys mean no unknown keys exist, so the any-setter forward
            // (a proven no-op here) is correctly skipped.
            sb.append("        if (input instanceof JqObject _o && _o.size() == ")
              .append(pojoPositional.size());
            for (int j = 0; j < pojoPositional.size(); j++) {
                var prop = pojoPositional.get(j);
                sb.append("\n                && _o.keyAt(").append(j).append(") == K_")
                  .append(prop.name().toUpperCase());
            }
            sb.append(") {\n");
            sb.append("            try {\n");
            int slot = 0;
            for (var prop : pojoPositional) {
                String statement = pojoWriteStatement(prop,
                        buildExtraction(prop, "_o.valueAt(" + (slot++) + ")", typeRefs));
                sb.append("                ").append(statement).append("\n");
            }
            sb.append("                return instance;\n");
            sb.append("            } catch (io.hyperfoil.tools.jjq.mapper.JqMapperException _e) {\n");
            sb.append("                // Fall through for precise failure paths\n");
            sb.append("            }\n");
            sb.append("        }\n");
        }

        if (!anyInfo.hasSetter()) {
            generateStrictCheck(sb, classSimpleName);
        }
        emitRequiredCheck(sb, classSimpleName, required);

        for (var prop : properties) {
            // Builder binding replaces the setter path wholesale (binders
            // below); skipping here keeps one loop, not two interleaved ones.
            if (builder != null) break;
            if (prop.ignored() || prop.skipDeserialize()) continue;
            // Creator-bound properties are already set (the creator owns
            // them); setters bind the rest. Mirrors the runtime rule.
            if (creatorWires.contains(prop.jsonName())) continue;
            String writeExpr;
            String optVar;
            if (prop.hasJqField()) {
                // Custom @JqField expression: absence is unprovable, keep the program
                String apply = "P_" + prop.name().toUpperCase() + ".apply(input)";
                writeExpr = buildExtraction(prop, apply, typeRefs);
                optVar = null;
            } else {
                // Single lookup: tryGet distinguishes absent keys (skip, keep
                // field initializers) from explicit nulls (write) with one probe.
                // K_ holds the interned key, so no equals runs at all. Aliases
                // fall back in priority order (literals: cold path, equals is fine).
                optVar = "_v_" + prop.name();
                sb.append("        var ").append(optVar).append(" = input.tryGet(K_")
                  .append(prop.name().toUpperCase()).append(");\n");
                for (String alias : prop.aliases()) {
                    sb.append("        if (").append(optVar).append(".isEmpty()) ").append(optVar)
                      .append(" = input.tryGet(\"").append(escapeJava(alias)).append("\");\n");
                }
                writeExpr = buildExtraction(prop, optVar + ".get()", typeRefs);
            }

            String statement = pojoWriteStatement(prop, writeExpr);
            if (statement == null) {
                // Private final field — read-only (the runtime path skips it too)
                continue;
            }
            if (prop.hasJqField()) {
                // Custom @JqField expression: absence is unprovable, write always
                sb.append("        ").append(statement).append("\n");
            } else if (isFalliblePojoExtraction(prop)) {
                // Fallible conversion: track the field in the failure path (issue #84)
                sb.append("        if (").append(optVar).append(".isPresent()) {\n");
                sb.append("            try {\n");
                sb.append("                ").append(statement).append("\n");
                sb.append("            } catch (io.hyperfoil.tools.jjq.mapper.JqMapperException _e) {\n");
                sb.append("                throw _e.prependPath(\"").append(escapeJava(prop.jsonName())).append("\");\n");
                sb.append("            }\n");
                sb.append("        }\n");
            } else {
                // Absent keys leave field initializers in place (issue #82).
                // Explicit nulls still take the write path.
                sb.append("        if (").append(optVar).append(".isPresent()) ")
                        .append(statement).append("\n");
            }
        }

        if (builder != null) {
            emitPojoBuilderBlock(sb, classSimpleName, properties, builder, typeRefs);
        }

        if (anyInfo.hasSetter()) {
            generateAnySetterForward(sb, "instance", anyInfo);
        }
        sb.append("        return instance;\n");
        sb.append("    }\n\n");

        // toJqValue: getter calls (serialization iterates the ordered view;
        // binding above stays declaration-ordered for constructor alignment)
        sortSerView(properties, JqMapperProcessor.PropertyInfo::jsonName, order);
        // Fused separator-key constants for the no-inclusion serialization
        // path (see the record generator); the POJO filter also drops
        // properties with no readable accessor, matching the appenders.
        if (!anyInfo.hasGetter() && properties.stream()
                .noneMatch(p -> !p.ignored() && !"ALWAYS".equals(p.inclusion()))
                && properties.stream()
                        .anyMatch(p -> !p.ignored() && !p.skipSerialize()
                                && resolvePojoReadExpr(p) != null)) {
            boolean firstKey = true;
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize() || resolvePojoReadExpr(prop) == null) continue;
                char prefix = firstKey ? '{' : ',';
                sb.append("    private static final String KEYF_").append(prop.name().toUpperCase())
                  .append(" = jsonKeyPrefixed(\"").append(escapeJava(prop.jsonName()))
                  .append("\", '").append(prefix).append("');\n");
                sb.append("    private static final byte[] KEYFB_").append(prop.name().toUpperCase())
                  .append(" = jsonKeyPrefixedBytes(\"").append(escapeJava(prop.jsonName()))
                  .append("\", '").append(prefix).append("');\n");
                firstKey = false;
            }
        }
        int activeCount = (int) properties.stream().filter(p -> !p.ignored()).count();
        boolean hasInclusion = properties.stream()
                .anyMatch(p -> !p.ignored() && !"ALWAYS".equals(p.inclusion()));

        sb.append("    @Override\n");
        sb.append("    public JqValue toJqValue(").append(classSimpleName).append(" instance, JqMapper mapper) {\n");

        if (!hasInclusion && !anyInfo.hasGetter()) {
            // Fast path: no inclusion filtering
            sb.append("        return JqObject.builder(").append(activeCount).append(")\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                sb.append("            .putUnchecked(\"").append(escapeJava(prop.jsonName())).append("\", ");
                generateSerializationValueForPojo(sb, prop, readExpr);
                sb.append(")\n");
            }
            sb.append("            .build();\n");
        } else if (!hasInclusion) {
            // Fast path with any-getter extras appended afterwards (issue #87)
            sb.append("        var _b = JqObject.builder(").append(activeCount).append(")\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                sb.append("            .putUnchecked(\"").append(escapeJava(prop.jsonName())).append("\", ");
                generateSerializationValueForPojo(sb, prop, readExpr);
                sb.append(")\n");
            }
            sb.append("            ;\n");
            sb.append("        putExtras(_b, ").append(anyGetterReadExpr(anyInfo)).append(", mapper);\n");
            sb.append("        return _b.build();\n");
        } else {
            // Inclusion filtering: keys unique — use putUnchecked
            sb.append("        var _b = JqObject.builder(").append(activeCount).append(");\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if ("ALWAYS".equals(prop.inclusion())) {
                    sb.append("        _b.putUnchecked(\"").append(escapeJava(prop.jsonName())).append("\", ");
                    generateSerializationValueForPojo(sb, prop, readExpr);
                    sb.append(");\n");
                } else {
                    generatePojoInclusionCheck(sb, prop, readExpr);
                }
            }
            if (anyInfo.hasGetter()) {
                sb.append("        putExtras(_b, ").append(anyGetterReadExpr(anyInfo)).append(", mapper);\n");
            }
            sb.append("        return _b.build();\n");
        }

        sb.append("    }\n\n");

        // appendJson — direct-to-JSON, bypasses JqValue tree
        generateAppendJsonForPojo(sb, classSimpleName, properties, anyInfo, mappedTypeNames);
        boolean buffered = !anyInfo.hasGetter() && properties.stream()
                .filter(p -> !p.ignored() && !p.skipSerialize())
                .allMatch(p -> p.converterClass() == null && p.adapter() == null && !p.stringShape()
                        && (p.format() != null
                                || isDirectBufferedType(p.typeName(), p.nestedMapped(), mappedTypeNames)));
        if (buffered) {
            emitBufferedWriterOptIn(sb);
            generateAppendJsonForPojo(sb, classSimpleName, properties, anyInfo, "CharOutput", mappedTypeNames);
        }

        // appendJsonBytes — direct-to-bytes, bypasses JqValue tree
        generateAppendJsonBytesForPojo(sb, classSimpleName, properties, anyInfo, mappedTypeNames);

        // type()
        sb.append("    @Override\n");
        sb.append("    public Class<").append(classSimpleName).append("> type() {\n");
        sb.append("        return ").append(classSimpleName).append(".class;\n");
        sb.append("    }\n");

        sb.append("}\n");
        return sb.toString();
    }

    /**
     * Generate appendJson for POJOs — same pattern as records but uses getter/field access.
     */
    private static void generateAppendJsonForPojo(StringBuilder sb, String classSimpleName,
                                                    List<JqMapperProcessor.PropertyInfo> properties,
                                                    JqMapperProcessor.AnyInfo anyInfo,
                                                    java.util.function.Predicate<String> mappedTypeNames) {
        generateAppendJsonForPojo(sb, classSimpleName, properties, anyInfo, "StringBuilder", mappedTypeNames);
    }

    private static void generateAppendJsonForPojo(StringBuilder sb, String classSimpleName,
                                                    List<JqMapperProcessor.PropertyInfo> properties,
                                                    JqMapperProcessor.AnyInfo anyInfo, String outputType,
                                                    java.util.function.Predicate<String> mappedTypeNames) {
        boolean hasInclusion = properties.stream()
                .anyMatch(p -> !p.ignored() && !"ALWAYS".equals(p.inclusion()));
        boolean fuse = !hasInclusion && properties.stream()
                .anyMatch(p -> !p.ignored() && !p.skipSerialize() && resolvePojoReadExpr(p) != null);

        sb.append("    @Override\n");
        sb.append("    public void appendJson(").append(classSimpleName)
          .append(" instance, ").append(outputType).append(" _sb, JqMapper mapper) {\n");
        if (anyInfo.hasGetter()) {
            // Any-getter extras need tree materialization — fall back (issue #87).
            // Emitting only the fallback: body after return would be unreachable code.
            sb.append("        toJqValue(instance, mapper).appendTo(_sb);\n");
            sb.append("    }\n\n");
            return;
        }
        if (!fuse) sb.append("        _sb.append('{');\n");

        if (!hasInclusion) {
            boolean first = true;
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if (!first && !fuse) sb.append("        _sb.append(',');\n");
                sb.append("        _sb.append(").append(fuse ? "KEYF_" : "KEY_")
                  .append(prop.name().toUpperCase()).append(");\n");
                appendJsonValueForPojo(sb, prop, readExpr, mappedTypeNames);
                first = false;
            }
        } else {
            sb.append("        boolean _sep = false;\n");
            for (var prop : properties) {
                if (prop.ignored() || prop.skipSerialize()) continue;
                String readExpr = resolvePojoReadExpr(prop);
                if (readExpr == null) continue;
                if ("ALWAYS".equals(prop.inclusion())) {
                    sb.append("        if (_sep) _sb.append(','); _sep = true;\n");
                    sb.append("        _sb.append(KEY_").append(prop.name().toUpperCase()).append(");\n");
                    appendJsonValueForPojo(sb, prop, readExpr, mappedTypeNames);
                } else {
                    appendJsonFieldWithInclusionForPojo(sb, prop, readExpr, mappedTypeNames);
                }
            }
        }

        sb.append("        _sb.append('}');\n");
        sb.append("    }\n\n");
    }

